function constants() {
    const greek = AXIS_MANIFEST.constants.filter(
        constant => constant.category === 'greek' && !constant.example,
    );
    const valued = AXIS_MANIFEST.constants.filter(
        constant => constant.category !== 'greek' || constant.example,
    );
    const operators = AXIS_MANIFEST.operators.map(operator =>
        entry(operator.name, operator.detail, operator),
    );
    const named = valued.map(constant => entry(constant.name, constant.detail, constant));
    const letters = greek.map(
        constant => `| ${code(constant.name)} | ${constant.detail.replace(/^Greek letter /, '')} |`,
    );
    return page(
        'Constants and operators',
        'The names Axis gives a meaning of their own: constants, Greek letters, and the bare words Desmos reads as operators.',
        2,
        `## Constants

${named.join('\n\n')}

## Greek letters

Written out, a Greek letter is drawn as the letter. It is a name like any other: it may be defined, used as a parameter, or left undefined for Desmos to offer as a slider.

| Name | Letter |
| ---- | ------ |
${letters.join('\n')}

## Operators

Words Desmos reads as operators rather than as functions or variables. None of them takes parentheses.

${operators.join('\n\n')}`,
    );
}

// ─────────────────────────────────────────────────────────────────────────────
// Keywords
// ─────────────────────────────────────────────────────────────────────────────

function keywords() {
    const statement = new Set(STATEMENT_KEYWORDS);
    const describe = ([name, info]) =>
        [`### ${name}`, info.detail + '.', info.documentation].join('\n\n');
    const all = Object.entries(KEYWORD_INFO);
    return page(
        'Keywords',
        'The words the language reserves, and what each one starts.',
        0,
        `A keyword is never a name: ${code('folder')} cannot be a variable. ${code('min')} and ${code('max')} are the exception - they mean something only after ${code('soft')}, and are the list functions everywhere else.

## Statements

${all
    .filter(([name]) => statement.has(name))
    .map(describe)
    .join('\n\n')}

## Everything else

${all
    .filter(([name]) => !statement.has(name))
    .map(describe)
    .join('\n\n')}`,
    );
}

// ─────────────────────────────────────────────────────────────────────────────
// Properties
// ─────────────────────────────────────────────────────────────────────────────

const VALUE_TYPES = {
    expression: 'any expression',
    number: 'a number',
    string: 'a string',
    boolean: `${code('true')} or ${code('false')}, or the name alone for ${code('true')}`,
    enum: 'one of its values',
    color: `a colour: a ${code('#hex')}, a [palette](#the-palette) name, or an expression`,
    range: `a range, ${code('lo..hi step s soft')}`,
    action: 'an action or a run of them',
    style: 'the name of a style',
};

const PLACEMENTS = {
    expression: 'an expression',
    folder: 'a folder',
    table: 'a table',
    column: 'a table column',
    image: 'an image',
    ticker: 'the ticker',
    import: 'an import',
    note: 'a note',
    config: `${code('config')}`,
    style: 'a style',
};

function property(definition, placements = placementsOf(definition.name)) {
    const facts = [`**Takes** ${VALUE_TYPES[definition.valueType]}.`];
    if (definition.values) facts.push(`**Values** ${definition.values.map(code).join(', ')}.`);
    if (placements.length) {
        facts.push(`**Written on** ${listOf(placements.map(placement => PLACEMENTS[placement]))}.`);
    }
    if (definition.repeatable) facts.push('May be given more than once.');
    return entry(definition.name, `${definition.detail}\n\n${facts.join(' ')}`, definition);
}

/** Which properties each placement takes, as the spec's §4.6 table has it. */
function placementTable() {
    const rows = AXIS_PROPERTY_PLACEMENTS.filter(placement => placement !== 'config').map(
        placement =>
            `| ${PLACEMENTS[placement]} | ${propertiesFor(placement)
                .map(definition => `[${code(definition.name)}](#${definition.name.toLowerCase()})`)
                .join(', ')} |`,
    );
    return `| Placement | Takes |\n| --------- | ----- |\n${rows.join('\n')}`;
}

function properties() {
    const metadata = AXIS_MANIFEST.metadata;
    // Grouped by where they go, which the manifest already says: whatever an
    // expression or a column takes, then whatever only images, or only
    // folders and imports, do.
    const on = placements => definition =>
        definition.appliesTo.some(placement => placements.includes(placement));
    const styling = metadata.filter(on(['expression', 'column']));
    const images = metadata.filter(d => !styling.includes(d) && on(['image'])(d));
    const folders = metadata.filter(d => !styling.includes(d) && !images.includes(d));
    const swatches = AXIS_PALETTE.map(
        color =>
            `| ${code(color.name)} | <span style="display:inline-block;width:1em;height:1em;border-radius:50%;background:${color.hex};vertical-align:middle"></span> ${code(color.hex)} |`,
    );

    return page(
        'Properties',
        'Every property written after an @: what it takes, and where it may go.',
        3,
        `Properties style the statement they trail: ${code('@ color: RED, lineWidth: 4')} inline, or ${code('@{ … }')} with one to a line. A property that is true or false may be written bare, as a flag: ${code('@ hidden')}. They are written the same way in a ${code('style')}, which is how a set of them is named and reused with ${code('use:')}.

Which properties are allowed depends on what they trail:

${placementTable()}

## Expressions, columns and styles

${styling.map(definition => property(definition)).join('\n\n')}

## Images

${images.map(definition => property(definition)).join('\n\n')}

## Folders and imports

${folders.map(definition => property(definition)).join('\n\n')}

## The ticker

The ${code('ticker')} statement takes a list of its own. Its ${code('playing')} is not a slider's: it starts the ticker rather than an animation.

${AXIS_MANIFEST.tickerProperties.map(definition => property(definition, ['ticker'])).join('\n\n')}

## The palette

The colours Desmos names, which ${code('color:')} takes by name. The names are case-sensitive: ${code('red')} is the product r·e·d.

| Name | Colour |
| ---- | ------ |
${swatches.join('\n')}`,
    );
}

