const CATEGORY_TITLES = {
    trig: 'Trigonometry',
    math: 'Arithmetic',
    statistics: 'Statistics',
    list: 'Lists',
    combinatorics: 'Combinatorics',
    geometry: 'Geometry',
    color: 'Colour',
    audio: 'Sound',
};

function functions() {
    const categories = [...new Set(AXIS_MANIFEST.functions.map(fn => fn.category))];
    const sections = categories.map(category => {
        const members = AXIS_MANIFEST.functions.filter(fn => fn.category === category);
        return [
            `## ${CATEGORY_TITLES[category] ?? category}`,
            ...members.map(fn =>
                entry(
                    fn.name,
                    `${code(snippetSignature(fn.snippet ?? `${fn.name}()`))} - ${fn.detail}`,
                    fn,
                ),
            ),
        ].join('\n\n');
    });
    return page(
        'Functions',
        `The ${AXIS_MANIFEST.functions.length} functions Axis knows, by category.`,
        1,
        `Every function here is Desmos' own, written as a call: ${code('sin(x)')}, ${code('mean(L)')}. A function of one list may also be written after it, as a member - ${code('L.mean')} is ${code('mean(L)')}.

A name that is none of these, called like one, is an error (${code('unknown-function')}) rather than the product of variables Desmos would take it for.

${sections.join('\n\n')}`,
    );
}

