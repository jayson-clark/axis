const SETTING_GROUPS = [
    ['boolean', 'Switches'],
    ['number', 'Numbers'],
    ['color', 'Colours'],
    ['string', 'Text'],
    ['enum', 'Choices'],
];

function settings() {
    const settings = AXIS_MANIFEST.configProperties;
    const known = new Set(SETTING_GROUPS.map(([type]) => type));
    const groups = [
        ...SETTING_GROUPS.map(([type, title]) => [
            title,
            settings.filter(definition => definition.valueType === type),
        ]),
        ['Everything else', settings.filter(definition => !known.has(definition.valueType))],
    ].filter(([, members]) => members.length);

    return page(
        'Settings',
        `The ${settings.length} calculator settings a config block takes.`,
        4,
        `A file's ${code('config { … }')} block sets up the calculator: the viewport, the grid, what the reader may change. It is written once, at the top level, one ${code('key: value')} to an entry.

${axis('config {\n    showGrid: false\n    xmin: -10; xmax: 10\n}\ny = sin(x)')}

${groups
    .map(
        ([title, members]) =>
            `## ${title}\n\n${members.map(definition => property(definition, [])).join('\n\n')}`,
    )
    .join('\n\n')}`,
    );
}

// ─────────────────────────────────────────────────────────────────────────────
// Diagnostics
// ─────────────────────────────────────────────────────────────────────────────

/** "a call on a name (§5.3)" as "A call on a name (§5.3)." */
const sentence = summary => summary[0].toUpperCase() + summary.slice(1) + '.';

/**
 * A code's entry. `also` is the checker's meaning for a code the lexer reports
 * too - `invalid-color` - written into the same entry rather than under a
 * second heading of its own, because the editors link a diagnostic to its
 * entry by the code alone, and a second heading with the same text would get
 * an anchor nothing links to.
 */
function diagnostic(code_, info, also) {
    const parts = [`### ${code_}`, sentence(info.summary), axis(info.example, `error="${code_}"`)];
    if (also) {
        parts.push(
            `The checker reports the same code for ${also.summary}.`,
            axis(also.example, `error="${code_}"`),
        );
    }
    return parts.join('\n\n');
}

function diagnostics() {
    const syntax = Object.entries(SYNTAX_DIAGNOSTICS);
    const compiler = Object.entries(COMPILER_DIAGNOSTICS).filter(
        ([name]) => !(name in SYNTAX_DIAGNOSTICS),
    );
    const decompiler = Object.entries(DECOMPILER_DIAGNOSTICS);
    return page(
        'Diagnostics',
        'Every problem Axis reports, by its code, with a file that causes it.',
        5,
        `Every problem is a diagnostic with a stable code, a message and the span of source it is about. None stops the rest of a file compiling: a value that is wrong is left off, a statement that cannot be written is left out, and the graph draws everything else.

Much of what is reported here is something Desmos would accept without a word - an unknown function name is a product of variables to it, and a colour it cannot read is ignored - which is why Axis says so instead.

## Reading the file

What the lexer and the parser report. After one of these, the parser picks up again at the next line.

${syntax.map(([name, info]) => diagnostic(name, info, COMPILER_DIAGNOSTICS[name])).join('\n\n')}

## Checking it

What the checker and the compiler report about a file that reads, but does not mean anything Desmos can draw.

${compiler.map(([name, info]) => diagnostic(name, info)).join('\n\n')}

## Decompiling a graph

What the decompiler reports, as warnings, about a graph it cannot write all of in Axis. The statement is still written, with a comment where the part it could not was.

| Code | What |
| ---- | ---- |
${decompiler.map(([name, info]) => `| ${code(name)} | ${sentence(info.summary)} |`).join('\n')}`,
    );
}

