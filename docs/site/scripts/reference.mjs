function overview() {
    const count = Object.keys;
    return page(
        'Reference',
        'Everything the language knows, generated from the compiler itself.',
        -1,
        `Every page in this section is generated from the packages that implement Axis - the manifest of names the compiler, the checker and the editor all read, and the catalogues of diagnostics they report - so it describes exactly the language the compiler accepts. Every example on these pages is compiled, and then drawn on a real Desmos calculator, before the site is published.

| Page | What is in it |
| ---- | ------------- |
| [Keywords](keywords/) | ${count(KEYWORD_INFO).length} reserved words, and the statements they start |
| [Functions](functions/) | ${AXIS_MANIFEST.functions.length} builtin functions |
| [Constants and operators](constants/) | ${AXIS_MANIFEST.constants.length} constants and ${AXIS_MANIFEST.operators.length} operators |
| [Properties](properties/) | ${AXIS_MANIFEST.metadata.length + AXIS_MANIFEST.tickerProperties.length} properties written after ${code('@')}, and the palette |
| [Settings](settings/) | ${AXIS_MANIFEST.configProperties.length} ${code('config')} settings |
| [Diagnostics](diagnostics/) | ${new Set([...count(SYNTAX_DIAGNOSTICS), ...count(COMPILER_DIAGNOSTICS), ...count(DECOMPILER_DIAGNOSTICS)]).size} diagnostic codes |

The [specification](../spec/) is the language's contract, written out in full.`,
        'Overview',
    );
}

/** Every page of the reference, by its path under `reference/`. */
export function referencePages() {
    return {
        'index.md': overview(),
        'keywords.md': keywords(),
        'functions.md': functions(),
        'constants.md': constants(),
        'properties.md': properties(),
        'settings.md': settings(),
        'diagnostics.md': diagnostics(),
    };
}
