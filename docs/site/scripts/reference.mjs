// The reference section, written out of the packages that define the language
// ═════════════════════════════════════════════════════════════════════════════
//
// Nothing here lists a name. Every function, operator, constant, keyword,
// property, setting, colour and diagnostic comes from the manifest, the
// keyword documentation or the diagnostic catalogues, and every grouping is
// derived from what those already say - a property's placements, a setting's
// value type - so an entry added there appears here with no edit, in the
// section it belongs to.

import {
    AXIS_MANIFEST,
    AXIS_PALETTE,
    AXIS_PROPERTY_PLACEMENTS,
    SYNTAX_DIAGNOSTICS,
    placementsOf,
    propertiesFor,
} from '@axis-dsl/syntax';
import { COMPILER_DIAGNOSTICS, DECOMPILER_DIAGNOSTICS } from '@axis-dsl/compiler';
import { KEYWORD_INFO, STATEMENT_KEYWORDS, snippetSignature } from '@axis-dsl/language-service';

/** A page's frontmatter and body. */
function page(title, description, order, body, label) {
    return [
        '---',
        `title: ${JSON.stringify(title)}`,
        `description: ${JSON.stringify(description)}`,
        `sidebar:\n  order: ${order}` + (label ? `\n  label: ${label}` : ''),
        '---',
        '',
        '<!-- Generated by docs/site/scripts/reference.mjs - edit the manifest, not this. -->',
        '',
        body.trim(),
        '',
    ].join('\n');
}

const axis = (source, meta = '') => '```axis' + (meta ? ` ${meta}` : '') + '\n' + source + '\n```';
const code = text => '`' + text + '`';

/** The detail, documentation and example of a manifest entry, in that order. */
function entry(heading, lead, item) {
    const parts = [`### ${heading}`, lead];
    if (item.documentation) parts.push(item.documentation);
    if (item.example) parts.push(axis(item.example));
    return parts.join('\n\n');
}

/** "a b c" as "a, b or c". */
function listOf(items) {
    if (items.length <= 1) return items.join('');
    return `${items.slice(0, -1).join(', ')} or ${items[items.length - 1]}`;
}

