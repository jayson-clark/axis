// ═════════════════════════════════════════════════════════════════════════════
// The examples section: one page per script in examples/scripts
// ═════════════════════════════════════════════════════════════════════════════
//
// Each script opens with a boxed title and a paragraph about itself, which
// become the page's title and introduction; the rest of the file is shown as
// written. The scripts are run through a real calculator by the harness'
// graph suite, so every one of these pages is a graph that draws.

import { readdirSync, readFileSync } from 'node:fs';
import { join } from 'node:path';

const RULE = /^\/\/ ─+$/;
const REPO = 'https://github.com/jayson-clark/axis/blob/main/examples/scripts';

/** The boxed header - title, then the comment paragraph under it - and the rest. */
function split(source) {
    const lines = source.split('\n');
    if (!RULE.test(lines[0]) || !RULE.test(lines[2])) {
        throw new Error('An example script has to open with a boxed title');
    }
    const title = lines[1].replace(/^\/\/\s*/, '');
    let end = 3;
    while (end < lines.length && lines[end].startsWith('//')) end++;
    const prose = lines
        .slice(3, end)
        .map(line => line.replace(/^\/\/ ?/, ''))
        .join('\n')
        .trim();
    return { title, prose, body: lines.slice(end).join('\n').trim() };
}

/** Every example, as pages by their path under `examples/`. */
export function examplePages(directory) {
    const pages = {};
    const names = readdirSync(directory)
        .filter(name => name.endsWith('.axis'))
        .sort(
            (a, b) =>
                Number(a.startsWith('showcase')) - Number(b.startsWith('showcase')) ||
                a.localeCompare(b),
        );

    names.forEach((name, order) => {
        const { title, prose, body } = split(readFileSync(join(directory, name), 'utf8'));
        // "Styling - colour, lines, …" is a name and what it covers; a
        // showcase is named by what follows "Showcase -".
        const [head, ...tail] = title.split(' - ');
        const showcase = head === 'Showcase';
        const label = showcase ? tail.join(' - ') : head;
        const description = showcase ? `A finished graph: ${label}.` : tail.join(' - ') || head;
        pages[name.replace(/\.axis$/, '.md')] = [
            '---',
            `title: ${JSON.stringify(label[0].toUpperCase() + label.slice(1))}`,
            `description: ${JSON.stringify(description)}`,
            `sidebar:\n  order: ${order}${showcase ? `\n  badge: Showcase` : ''}`,
            '---',
            '',
            `<!-- Generated by docs/site/scripts/examples.mjs from examples/scripts/${name}. -->`,
            '',
            prose,
            '',
            `[\`examples/scripts/${name}\`](${REPO}/${name})`,
            '',
            '```axis',
            body,
            '```',
            '',
        ].join('\n');
    });
    return pages;
}
